// Manual backup and recovery rehearsal. Never overwrites an existing database.
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const { existsSync, readFileSync } = require('node:fs')
const { spawn } = require('node:child_process')
const { createHash } = require('node:crypto')
const mysql = require('mysql2/promise')
require('dotenv').config({ path: path.join(__dirname, '../.env'), quiet: true })
const settingsPath = path.join(__dirname, '../backup.config.json')
const settings = existsSync(settingsPath) ? JSON.parse(readFileSync(settingsPath, 'utf8')) : {}
const directory = path.resolve(process.env.BACKUP_DIR || settings.directory || path.join(__dirname, '../../.private-backups'))
const bin = process.env.MYSQL_BIN || 'C:/Program Files/MySQL/MySQL Server 8.0/bin'
const config = { host: process.env.DB_HOST, port: Number(process.env.DB_PORT || 3306), user: process.env.DB_USER, password: process.env.DB_PASSWORD }
const hash = bytes => createHash('sha256').update(bytes).digest('hex')
async function main() {
  await fs.mkdir(directory, { recursive: true })
  const mode = process.argv[2] || 'create'
  if (!['create', 'verify'].includes(mode)) throw Error('Uso: node scripts/backup.cjs create | verify ARCHIVO.sql')
  const source = process.env.DB_NAME
  if (!source) throw Error('Falta DB_NAME.')
  // Keep credentials out of backup folders (which may be synchronized by OneDrive).
  const credentialsDirectory = await fs.mkdtemp(path.join(os.tmpdir(), 'taller-backup-'))
  const credentials = path.join(credentialsDirectory, 'mysql.cnf')
  const quote = value => '"' + String(value).replaceAll('\\', '\\\\').replaceAll('"', '\\"').replaceAll('\n', '\\n').replaceAll('\r', '\\r') + '"'
  await fs.writeFile(credentials, '[client]\n' + Object.entries(config).map(([k,v]) => `${k}=${quote(v ?? '')}`).join('\n'), { mode: 0o600, flag: 'wx' })
  let conn
  async function run(tool, args, input) {
    await new Promise((resolve, reject) => {
      const child = spawn(path.join(bin, tool + (process.platform === 'win32' ? '.exe' : '')), [`--defaults-extra-file=${credentials}`, ...args], { windowsHide: true, stdio: ['pipe','ignore','pipe'] })
      let errors = ''
      child.stderr.on('data', data => { errors += data })
      child.on('error', reject)
      child.on('close', code => code === 0 ? resolve() : reject(Error(`${tool}: ${errors.trim()}`)))
      child.stdin.on('error', () => {})
      child.stdin.end(input)
    })
  }
  const dump = (name, file) => run('mysqldump', ['--single-transaction','--routines','--events','--triggers','--hex-blob','--order-by-primary','--skip-comments','--skip-add-locks','--no-tablespaces','--set-gtid-purged=OFF','--default-character-set=utf8mb4', `--result-file=${file}`, name])
  try {
    conn = await mysql.createConnection(config)
    let file, manifest
    if (mode === 'create') {
      const [engines] = await conn.query("SELECT TABLE_NAME FROM information_schema.TABLES WHERE TABLE_SCHEMA=? AND TABLE_TYPE='BASE TABLE' AND ENGINE <> 'InnoDB'", [source])
      if (engines.length) throw Error('Hay tablas no transaccionales: se requiere respaldo con mantenimiento programado.')
      file = path.join(directory, `taller-${new Date().toISOString().replace(/[:.]/g,'-')}.sql`)
      const partial = file + '.partial'
      await dump(source, partial)
      await fs.rename(partial, file)
      manifest = { version: 1, createdAt: new Date().toISOString(), source, sha256: hash(await fs.readFile(file)), verified: false }
      await fs.writeFile(file + '.json', JSON.stringify(manifest,null,2))
      console.log('Respaldo creado:', file)
      console.log('Para verificar: node scripts/backup.cjs verify "' + file + '"')
      return
    }
    if (!process.argv[3]) throw Error('Indica el archivo SQL generado por create.')
    file = path.resolve(process.argv[3])
    manifest = JSON.parse(await fs.readFile(file + '.json','utf8'))
    const contents = await fs.readFile(file)
    if (hash(contents) !== manifest.sha256) throw Error('El respaldo no coincide con su SHA-256. No se importó.')
    // Only dumps generated by this script: no database-switching statements.
    if (/^\s*(?:USE\s|CREATE\s+DATABASE|DROP\s+DATABASE)/im.test(contents.toString())) throw Error('El SQL contiene instrucciones para cambiar de base.')
    const target = `taller_restore_${Date.now()}`
    if (!/^taller_restore_\d+$/.test(target) || target === source) throw Error('Destino inválido.')
    await conn.query(`CREATE DATABASE \`${target}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci`)
    console.log('Recuperación aislada:', target)
    await run('mysql', ['--binary-mode','--default-character-set=utf8mb4',target],contents)
    const recovered = file + '.recovered.sql'
    await dump(target,recovered)
    // MySQL may explicitly emit a charset already implied by the column collation.
    const normalize = value => value.toString('utf8').replace(/^(  `[^`]+` .*?) CHARACTER SET utf8mb4 COLLATE utf8mb4_/gm, '$1 COLLATE utf8mb4_')
    const same = hash(normalize(await fs.readFile(recovered))) === hash(normalize(contents))
    if (!same) throw Error('La exportación recuperada difiere del respaldo. Conservar ambos archivos para revisar.')
    const [tables] = await conn.query("SELECT TABLE_NAME FROM information_schema.TABLES WHERE TABLE_SCHEMA=? AND TABLE_TYPE='BASE TABLE'",[target])
    const counts = {}
    for (const { TABLE_NAME: table } of tables) {
      const [[row]] = await conn.query(`SELECT COUNT(*) AS n FROM \`${target}\`.${mysql.escapeId(table)}`)
      counts[table] = row.n
    }
    await fs.writeFile(file + '.json',JSON.stringify({...manifest,verified:true,verifiedAt:new Date().toISOString(),recoveryDatabase:target,verification:'SQL y datos recuperados idénticos tras normalizar declaraciones redundantes CHARACTER SET utf8mb4 en columnas; SHA-256 del archivo original validado.',counts},null,2))
    await fs.unlink(recovered)
    console.log(JSON.stringify({verified:true,recoveryDatabase:target,tables:tables.length,records:Object.values(counts).reduce((a,b)=>a+b,0)},null,2))
  } finally {
    await conn?.end()
    await fs.unlink(credentials).catch(()=>{})
    await fs.rmdir(credentialsDirectory).catch(()=>{})
  }
}
main().catch(error => { console.error(error.message || error.code || 'No se pudo conectar con MySQL. Comprueba el servicio y la configuración.'); process.exitCode=1 })
